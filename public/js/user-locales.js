export const DEFAULT_LANG = 'en';

function canUseLocalStorage() {
    try {
        return typeof window !== 'undefined' && window.localStorage != null;
    } catch {
        return false;
    }
}

let currentLang = canUseLocalStorage()
    ? (window.localStorage.getItem('app_language') || DEFAULT_LANG)
    : DEFAULT_LANG;

export function getLanguage() {
    return currentLang;
}

export function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        if (canUseLocalStorage()) {
            window.localStorage.setItem('app_language', lang);
        }
    }
}

export function t(key, params = {}) {
    const langData = translations[currentLang] || translations[DEFAULT_LANG];
    let message = langData[key] || key;
    for (const [k, v] of Object.entries(params)) {
        message = message.replace(new RegExp(`\{${k}\}`, 'g'), v);
    }
    return message;
}
